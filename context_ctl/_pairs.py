# -*- coding: utf-8 -*-
"""Кто кому хозяин: судьбу вызова инструмента решает судьба его РЕЗУЛЬТАТА.

ПРАВИЛО, сформулированное владельцем 2026-09-22 и проверенное на всей базе:

    проза     → судьба СВОЕГО сообщения
    вызов     → судьба СВОЕГО результата
    оболочка  → жива, пока в ней есть хоть проза, хоть один вызов

Две судьбы, два уже существующих адреса. Поэтому вызову НЕ нужно собственного имени: ткнули
в `m0005` — решили судьбу вызова, ткнули в `m0004` — решили судьбу прозы. Субадрес
(`m0004.c1`) обсуждался и отвергнут: лишняя поверхность для человека там, где хватает двух
имеющихся.

ЗАЧЕМ ЭТО ВООБЩЕ. Компакция была единственной операцией, которая умела съесть результат в
одиночку, оставив вызов сиротой, — и тогда `lint_pairs` отказывал ЦЕЛИКОМ. Живой случай
2026-09-22, сессия `20260902_085526_e8db95`: дырка в выборе пришлась на `m0004` (вызов
`vision_analyze`), а его результат `m0005` попал в съедаемое. Отказ был честный, но человеку
он предлагал «сдвинь край диапазона», хотя разрезала не граница, а дырка в середине.

ОСТАЛЬНЫЕ ОПЕРАЦИИ ЭТОМУ ПРАВИЛУ УЖЕ ПОДЧИНЯЮТСЯ — мы просто никогда его не записывали:

    drop content  строка результата ОСТАЁТСЯ, тело подменяется заглушкой → хозяин жив
    erase tool    уходят обе строки                                      → хозяин мёртв
    erase turn    массовое, уходит всё                                   → хозяин мёртв

Перевод `erase`/`drop` на этот модуль — отдельная работа: они сегодня работают и своё делают
правильно. Модуль написан снаружи компакции именно затем, чтобы им было куда переехать.

ДВА ЗАМЕРА ПО ВСЕЙ ЖИВОЙ БАЗЕ (7528 реплик ассистента с вызовами, 2026-09-22), из-за которых
правило не может быть «по реплике целиком»:

    вызовов в одной реплике: {1: 6086, 2: 652, 3: 390, 4: 145, 5: 98, 6: 52, … 24: 1}
    реплик с НЕСКОЛЬКИМИ вызовами:     1442  (19%)
    реплик, где есть И проза И вызов:  4187  (56%)
    реплик с пустой прозой:            3341  (44%)

Первое: у одной реплики хозяев несколько, и решают они по-разному — значит разбираем вызовы
ПОШТУЧНО. Второе: «реплика с вызовом — это пустышка» верно меньше чем в половине случаев, и
предположение это ломает; сессия `20260917_013139_ae86e7`, на которой правило придумывалось,
оказалась нетипичной — там пусты все пять.

ЧТО МЫ НЕ ТЕРЯЕМ, убивая вызов вместе с утонувшим результатом. Ничего: `_distill.zoned_block`
отдаёт рендереру ВЕСЬ кусок, и в блоке данных лежат и `TOOL-call`, и `TOOL-result` (обрезанные
по категории). Содержимое утонувшего результата в дистилляте учтено. Комментарий в `_compact`
про «суммаризатору их не увидит» врал — правится тем же заходом.

АДРЕС ПРИ ЭТОМ НЕ ЕДЕТ, и это не удача. Личность сообщения — `_msgindex.place()` —
это `(роль, время)`, БЕЗ дайджеста содержимого; разделение оплачено живой проверкой
2026-09-09 ровно на этом случае («`erase` переписывает `tool_calls`, `drop content` — тело
тул-ответа; сообщение то же, содержимое другое»). Отсюда единственное правило правки:

    **`role` и `timestamp` не трогаем НИКОГДА.**

ЛОВУШКА ПРЕДОХРАНИТЕЛЯ, про которую обязан знать вызывающий. `_apply._row_key` ключует строку
ассистента ПО ТЕКСТУ, а не по координате. Выпотрошив прозу, мы меняем ключ — и предохранитель
коммита увидит исходную строку базы как непосчитанную и откажет целиком. Поэтому ИСХОДНЫЕ
версии всех правленых строк обязаны уехать в `removed` (тот же законный вход, что у `erase`):
прежняя версия строки действительно ушла, новая лежит в списке. Возвращаем их в `was`.
"""

from __future__ import annotations

from . import _addresses, _prompts, _stubs


# Разбор вызовов, хозяева, носители и достройка выбора живут в `_addresses.py` (Plan16-Task06,
# 2026-09-28): правило одно на все операции, и выгрузке оно нужно не меньше, чем компакции.
# Здесь — прежние имена, чтобы вызывающие и тесты не переезжали разом.
calls_of = _addresses.calls_of
owners = _addresses.owners
carriers = _addresses.carriers


def expand(rows, chosen) -> tuple:
    """Достройка выбора компакции. Правило и его довод — `_addresses.expand_positions`."""
    return _addresses.expand_positions("compact", rows, chosen)


def settle(rows, eaten) -> dict:
    """Применить правило владения к набору съедаемых позиций.

    `eaten` — позиции строк, которые человек назначил в дистиллят. Возвращает:

        {"eaten": set,            что тонет НА САМОМ ДЕЛЕ (может стать меньше: оболочки)
         "patch": {поз: строка|None},  чем заменить строку; `None` — строки не будет вовсе
         "was":   {поз: строка},   ИСХОДНЫЕ версии правленых строк — для `removed`
         "notes": [str]}           человеку в отчёт: лечение должно быть заметным

    ПРАВКИ БЫВАЮТ И СНАРУЖИ ПРОЛЁТА, и это не ошибка. Если результат на первой съедаемой
    позиции, а его вызов лежит строкой ВЫШЕ — то есть вне выбора вовсе, — умерший хозяин
    забирает вызов из чужой, никем не выбранной реплики. Ровно этот случай раньше давал
    «граница диапазона разрезала бы пару».

    ДЫРКИ ВНУТРИ БЛОКА НЕ БЫВАЕТ, и это стоит сказать прямо, потому что я на этом ошибся.
    Результаты одной реплики идут подряд сразу за ней. Съешь любой из них — по правилу
    владения вместе с ним уходит и его вызов, то есть пара исчезает целиком, а оставшиеся
    вызовы остаются впритык к оставшимся результатам. Разрыву взяться неоткуда.

    Разорвать блок может ТОЛЬКО ВСТАВКА, а вставок ровно две: дистиллят на месте первого
    съеденного и закрывающая строка за последним. Их и сторожим — `_insertion_break`, и
    только их. Прежняя версия сторожила весь блок целиком: вытаскивала обратно КАЖДЫЙ
    съеденный результат, лежащий до последнего выжившего. На живом прогоне 2026-09-22 это
    вернуло к жизни `m0005`, который владелец выбрала к съедению, при том что ни одна
    вставка внутрь того блока и близко не попадала.
    """
    out = _resolve(rows, set(eaten or []))
    _drop_old_brackets(rows, out)
    return out


def _drop_old_brackets(rows, out) -> None:
    """Убрать закрывающие строки ПРОШЛЫХ компакций, попавшие в зону работ.

    Решение владельца 2026-09-22: «все скобки, которые попадают в зону дистилляции, должны
    быть удалены при реконструкции, и в пузырёк никогда не могли попасть».

    Довод простой и сильный. Закрывающая строка — не содержание, а знак ГРАНИЦЫ: «между
    сжатым блоком и этой линией ходы стоят дословно». Внутри нового сжатого блока такая
    граница не описывает ничего: то, о чём она говорила, только что уехало в дистиллят.
    Оставить её пузырьком — значит выдать чужой структурный знак за ход разговора, да ещё с
    ярлыком «остаётся дословно, опирайся на него».

    Съеденную скобку убирать не нужно — она и так тонет. Правим только ту, что оказалась
    дыркой в выборе: она не попадёт ни в пузырьки (`run_over` вычтет её как убранную), ни в
    ленту. Новую границу поставит новая компакция, одну и на месте.
    """
    eaten = out["eaten"]
    if not eaten:
        return
    first, last = min(eaten), max(eaten)
    for index in range(first, last + 1):
        if index in eaten or index in out["patch"]:
            continue
        row = (rows or [])[index] if 0 <= index < len(rows or []) else None
        if not isinstance(row, dict):
            continue
        if _prompts.is_distill_end(str(row.get("content") or "")):
            out["was"][index] = row
            out["patch"][index] = None
            out["notes"].append(
                f"позиция {index}: закрывающая строка прежней компакции убрана — внутри "
                "нового сжатого блока она описывает границу, которой больше нет")


def _block_around(rows, eaten, point):
    """Живой блок «реплика + её выжившие результаты», внутрь которого попала бы точка.

    `(начало, конец)` или `None`. Начало — сама реплика, конец — её последний выживший
    результат. Живой блок это строка ассистента, которая ОСТАЁТСЯ в ленте и держит вызов,
    чей результат тоже остаётся.
    """
    eaten = set(eaten or [])
    owner_at = owners(rows)
    start = end = None
    for index, row in enumerate(rows or []):
        if index > point or index in eaten:
            continue
        if not isinstance(row, dict) or str(row.get("role") or "") != "assistant":
            continue
        for call in calls_of(row):
            place = owner_at.get(_stubs._call_id(call))
            # Вызов жив, а его результат лежит ЗА точкой — значит точка внутри блока.
            if place is not None and place not in eaten and place > point:
                start = index if start is None else min(start, index)
                end = place if end is None else max(end, place)
    return None if start is None else (start, end)


def insert_left(rows, eaten, point):
    """Куда поставить ДИСТИЛЛЯТ, чтобы он не оказался внутри живого блока.

    Обычно — на место первого съеденного, как и было. Но если это место лежит между живой
    репликой с вызовом и её выжившим результатом, вставка съезжает на **первое валидное
    место слева**, то есть перед самой репликой (решение владельца, 2026-09-22).

    ПОЧЕМУ ДВИГАЕМ ВСТАВКУ, А НЕ ОТМЕНЯЕМ ВЫБОР. Прежняя версия в этом случае выводила
    съеденный результат обратно в живые — и на разборе живого примера оказалось, что
    лекарство хуже болезни: человек просил съесть реплику и один из её результатов, а
    вытащенный результат оживлял вызов, вызов расформировывал оболочку, и от заказа не
    оставалось ничего. Порядок ленты вставка не портит: дистиллят просто встаёт на строку
    раньше, чем мог бы.
    """
    block = _block_around(rows, eaten, point)
    return point if block is None else min(point, block[0])


def insert_right(rows, eaten, point):
    """Куда поставить ЗАКРЫВАЮЩУЮ строку. Зеркально `insert_left`, но сдвиг ВПРАВО.

    Влево её двигать нельзя: она закрывает съеденный кусок, и уехав налево, оставила бы
    пузырьки блока снаружи скобок — то есть соврала бы о границе. Поэтому пропускаем блок
    целиком и встаём за его последним выжившим результатом.
    """
    block = _block_around(rows, eaten, point)
    return point if block is None else max(point, block[1])


def _resolve(rows, eaten) -> dict:
    """Один проход правила владения по готовому набору. Ничего не вытаскивает обратно."""
    eaten = set(eaten or [])
    owner_at = owners(rows)
    patch: dict = {}
    was: dict = {}
    notes: list = []

    for index, row in enumerate(rows or []):
        if not isinstance(row, dict) or str(row.get("role") or "") != "assistant":
            continue
        calls = calls_of(row)
        if not calls:
            continue

        alive, doomed = [], []
        for call in calls:
            place = owner_at.get(_stubs._call_id(call))
            # Вызов БЕЗ результата в ленте — уже сломанная пара, и сломана не нами. Своей
            # судьбы у него нет, поэтому он разделяет судьбу строки: чинить чужую поломку
            # молча мы не беремся, но и усугублять её не станем.
            if place is None:
                (doomed if index in eaten else alive).append(call)
            else:
                (doomed if place in eaten else alive).append(call)

        if len(alive) == len(calls) and index not in eaten:
            continue                                   # ничего не изменилось

        has_prose = bool(str(row.get("content") or "").strip())

        if alive:
            # Хоть один хозяин выжил → строка обязана остаться. Если её съедали, она
            # выходит из съедаемого ОБОЛОЧКОЙ: проза ушла в дистиллят, вызовы остались.
            fresh = {**row, "tool_calls": alive}
            if index in eaten:
                fresh["content"] = ""
                eaten.discard(index)
                notes.append(
                    f"позиция {index}: реплика оставлена оболочкой — её прозу съел "
                    f"дистиллят, но {len(alive)} вызов(ов) пережили свои результаты")
            else:
                notes.append(
                    f"позиция {index}: из живой реплики убрано вызовов "
                    f"{len(doomed)} — их результаты ушли в дистиллят")
            was[index] = row
            patch[index] = fresh
            continue

        if index in eaten:
            continue                                   # тонет обычным порядком, целиком

        # Живая строка потеряла ВСЕ вызовы: их хозяева утонули.
        was[index] = row
        if has_prose:
            patch[index] = {**row, "tool_calls": []}
            notes.append(f"позиция {index}: у живой реплики убраны все вызовы "
                         f"({len(doomed)}) — их результаты ушли в дистиллят; проза цела")
        else:
            # Ни прозы, ни вызовов — сообщение ассистента ни с чем. Убираем целиком:
            # пустой ход провайдеру отдавать нельзя, а хранить его незачем.
            patch[index] = None
            notes.append(f"позиция {index}: пустая реплика ассистента убрана — "
                         "она несла только вызовы, и все их результаты утонули")

    return {"eaten": eaten, "patch": patch, "was": was, "notes": notes}
